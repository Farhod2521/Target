"""The choice an answer may end with, split off before anybody reads it.

**A button is never built out of a sentence.** The assistant writes prose
and, when one of the actions it was handed is the answer, ends with a line
naming that action's key. The key is the whole of what the model decides:
the verb on the button, the advert it acts on and the service behind it all
come from the card the product built, and a key that was not in the list it
was given resolves to nothing at all.

That is the difference between offering a choice and letting a model invent
one. Asked to write its own button, a model eventually writes "Byudjetni
ikki barobar oshirish" for an account whose ceiling forbids it - a promise
in the product's own voice that nothing behind it can keep.

The marker is stripped as it streams, not afterwards. Everything here runs
one chunk at a time in front of :class:`~core.chat.verify.FigureGate`, so a
half-arrived marker is held back rather than shown and then taken away.

**A reply is the other thing an answer may end with.** When the assistant
has asked the owner something, it may end with a line of short answers to
it, and each becomes a button that sends its own words back as the owner's
next message. Those words *are* the model's - there is nothing behind a
reply to read them out of - and that is safe for the reason an action
would not be: a reply changes nothing. It is a message the owner could have
typed, sent through the same question box and counted against the same
allowance. What is still checked is the figures in it - see
:func:`vetted_replies`.

Django-free, like everything in ``core``: it is given text and answers with
text.
"""

import re
from dataclasses import dataclass, field
from typing import Final

from core.chat.verify import FigureGate

# What the model writes to name a choice. Two per cent signs on each side
# because the answer is Markdown and this must not be mistaken for any of
# it - a bare word would eventually appear in a sentence about the product
# itself, and a Markdown construct would be rendered before it was read.
MARK: Final = "%%CHOICE%%"

# The shape of a key, as generated by ``apps.chat.selectors.choices``. A
# letter and a digit or two: short enough to cost nothing in the context,
# structured enough that a stray "2" in the model's closing line is not
# mistaken for one.
KEY: Final = re.compile(r"\b([A-Z]\d{1,2})\b")

# How many buttons one answer may carry.
#
# Two, and it is a product decision rather than a technical one. Three
# buttons under a paragraph is a menu, and a menu is what this screen is
# not: the assistant answers a question and offers the one or two things
# that answer follows on to. The rest are on the screen that lists them.
MAX_CHOICES: Final = 2

# What the model writes to offer answers to its own question. A second
# marker rather than a second shape of the first: an action is a key into
# a closed list and a reply is free words, and a line that could be either
# would be read as whichever did the more harm.
REPLY_MARK: Final = "%%REPLY%%"

# What separates one reply from the next on that line.
REPLY_SEPARATOR: Final = "|"

# How many replies one answer may carry. Five, and usually fewer: the
# owner's decision. A question with two sensible answers gets two, and a
# question that is not asked gets none.
MAX_REPLIES: Final = 5

# How long one reply may be. A button is read at a glance and on a phone;
# a reply longer than this is a sentence, and a sentence is what the box
# under the buttons is for. Dropped rather than cut - half a sentence sent
# in the owner's name is worse than one button fewer.
REPLY_MAX_CHARS: Final = 48

# The quotation marks a model puts round a reply it thinks of as a quote.
# The button is the quotation; the marks would be sent as part of it.
_QUOTES: Final = "\"'«»“”„`"

_MARKS: Final = (MARK, REPLY_MARK)


def _held(text: str) -> str:
    """The trailing part of ``text`` that could still become the marker.

    A chunk boundary lands anywhere - Claude's pieces end mid-word as
    readily as mid-sentence - so "…javob %%CHO" has to be held rather than
    shown. Only a proper prefix is held: a complete marker is handled by
    the caller before this is asked.
    """
    longest = max(len(mark) for mark in _MARKS) - 1
    for size in range(min(longest, len(text)), 0, -1):
        if any(mark.startswith(text[-size:]) for mark in _MARKS):
            return text[-size:]
    return ""


def _first_mark(buffer: str) -> tuple[int, str]:
    """Where the earliest marker starts in ``buffer``, and which one it is."""
    found = [(at, mark) for mark in _MARKS if (at := buffer.find(mark)) >= 0]
    return min(found) if found else (-1, "")


@dataclass(slots=True)
class ChoiceGate:
    """Passes an answer through, keeping the choice line to itself.

    Stateful across chunks for the same reason the figure gate is: the
    thing being looked for arrives in pieces, and a gate that judged each
    piece on its own would show half a marker to somebody reading.

    A marker in the middle of an answer costs one line rather than the
    rest of the answer. The prompt says to put it last and it does; a
    model that puts it somewhere else should lose the line it wrote it on
    and nothing more.
    """

    keys: tuple[str, ...] = ()
    replies: tuple[str, ...] = ()
    _tail: str = field(default="", repr=False)
    # Which marker the line being read began with, or nothing.
    _marked: str = field(default="", repr=False)

    def feed(self, text: str) -> str:
        """The part of ``text`` that is prose, with any choice line removed."""
        out: list[str] = []
        buffer = self._tail + text
        self._tail = ""

        while buffer:
            if self._marked:
                line, newline, rest = buffer.partition("\n")
                if not newline:
                    # The line is not finished: a reply cut at a chunk
                    # boundary would be two half-replies. Held whole until
                    # its newline or the end of the stream.
                    self._tail = line
                    break
                self._take(line)
                self._marked = ""
                buffer = rest
                continue

            at, mark = _first_mark(buffer)
            if at >= 0:
                out.append(buffer[:at])
                self._marked = mark
                buffer = buffer[at + len(mark) :]
                continue

            held = _held(buffer)
            out.append(buffer[: len(buffer) - len(held)] if held else buffer)
            self._tail = held
            break

        return "".join(out)

    def flush(self) -> str:
        """Whatever was held back and turned out not to be a marker."""
        held, self._tail = self._tail, ""
        if self._marked:
            self._take(held)
            self._marked = ""
            return ""
        return held

    def _take(self, line: str) -> None:
        if self._marked == REPLY_MARK:
            self._take_replies(line)
        else:
            self._take_keys(line)

    def _take_replies(self, line: str) -> None:
        """Read the offered answers out of a reply line, in the order written.

        Each is trimmed of the quotation marks a model puts round words it
        thinks of as quoted, and one that is empty, too long or already
        offered is dropped rather than repaired.
        """
        found = list(self.replies)
        seen = {reply.casefold() for reply in found}
        for part in line.split(REPLY_SEPARATOR):
            reply = " ".join(part.split()).strip(_QUOTES).strip()
            if not reply or len(reply) > REPLY_MAX_CHARS:
                continue
            if reply.casefold() in seen:
                continue
            seen.add(reply.casefold())
            found.append(reply)
        self.replies = tuple(found[:MAX_REPLIES])

    def _take_keys(self, line: str) -> None:
        """Read keys out of the choice line, in the order they were written.

        Deduplicated and capped. The order is the model's, which is the one
        thing about the presentation it decides: it read the question and
        the two actions are not equally likely to be the answer.
        """
        found = list(self.keys)
        for key in KEY.findall(line):
            if key not in found:
                found.append(key)
        self.keys = tuple(found[:MAX_CHOICES])


def vetted_replies(
    replies: tuple[str, ...], *, allowed: frozenset[str], quoted: frozenset[str]
) -> tuple[str, ...]:
    """The replies whose figures the answer's own gate would have let through.

    A reply is the model's words and goes out unread by anything else, so
    a figure in it gets the check every figure in the answer gets. One
    that would have been masked costs its button: a reply with a hole in
    it cannot be sent, and a reply with an invented price in it would be
    sent as though the owner had said it.
    """
    kept: list[str] = []
    for reply in replies:
        gate = FigureGate(allowed=allowed, quoted=quoted)
        gate.feed(reply)
        gate.flush()
        if not gate.masked:
            kept.append(reply)
    return tuple(kept)


